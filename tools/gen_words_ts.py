"""words.json + phrases.json (sound/<name>/voice) -> studio/src/videos/<name>/words.ts (frame-accurate word table).
Usage: python gen_words_ts.py <voice_dir> <out.ts>"""
# GUARD (2026-11-11): since the ElevenLabs re-time the picture keeps the OLD voice clock (words.ts = the Kokoro take in
# sound/antitheft/voice/_kokoro_v3/) and voicewarp.ts maps it onto the new narration. Regenerating words.ts from the new
# words.json would shift every BEAT: refuse unless --force.
import json as _json, os as _os, sys as _sys
_vi = _os.path.join(_sys.argv[1], "voice_info.json") if len(_sys.argv) > 1 else ""
if _vi and _os.path.isdir(_os.path.join(_sys.argv[1], "_kokoro_v3")) and _os.path.exists(_vi) and str(_json.load(open(_vi, encoding="utf-8")).get("take", "")).startswith("eleven") and "--force" not in _sys.argv:
    _sys.exit("gen_words_ts.py: the voice dir holds the ElevenLabs take; words.ts must stay on the old clock (use tools/voice_warp.py). --force to override.")
import json
import sys
from pathlib import Path

vd, out = Path(sys.argv[1]), Path(sys.argv[2])
words = json.loads((vd / "words.json").read_text(encoding="utf-8"))
phr = json.loads((vd / "phrases.json").read_text(encoding="utf-8"))
FPS = 30
def phrase_of(t):
    for q in phr:
        if q["s"] - 0.02 <= t <= q["e"] + 0.02:
            return q["i"]
    return min(phr, key=lambda q: abs(q["s"] - t))["i"]


L = ["// GENERATED by tools/gen_words_ts.py from sound/antitheft/voice/words.json + phrases.json. Do not edit by hand:",
     "// re-run the generator after any voice change (and re-run the sound mix).",
     "export type Word = { w: string; s: number; e: number; f: number; fe: number; p: number };  // p = phrase index (voice_build.py P)",
     "export const WORDS: Word[] = ["]
for w in words:
    L.append(f"  {{ w: {json.dumps(w['w'])}, s: {w['s']:.3f}, e: {w['e']:.3f}, f: {round(w['s'] * FPS)}, fe: {round(w['e'] * FPS)}, p: {phrase_of((w['s'] + w['e']) / 2)} }},")
L.append("];")
L.append("export type Phrase = { i: number; beat: number; s: number; e: number; f: number; fe: number; text: string; style: string | null };")
L.append("export const PHRASES: Phrase[] = [")
for p in phr:
    L.append(f"  {{ i: {p['i']}, beat: {p['beat']}, s: {p['s']:.3f}, e: {p['e']:.3f}, f: {round(p['s'] * FPS)}, fe: {round(p['e'] * FPS)}, "
             f"text: {json.dumps(p['markup'])}, style: {json.dumps(p['style'])} }},")
L.append("];")
L.append(f"export const VOICE_END_F = {round(words[-1]['e'] * FPS)};")
L += [
    "const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9%']/g, \"\");",
    "/** index of the n-th word equal to `w` (punctuation/case ignored) at or after word index `from` */",
    "export const wi = (w: string, from = 0, n = 0) => {",
    "  let k = 0;",
    "  for (let i = from; i < WORDS.length; i++) if (norm(WORDS[i].w) === norm(w)) { if (k === n) return i; k++; }",
    "  throw new Error(`word not found: ${w} from ${from}`);",
    "};",
    "/** start frame of a word, found after another word: W(\"steal\") or W(\"steal\", \"wanted\") */",
    "export const W = (w: string, after?: string) => WORDS[wi(w, after ? wi(after) : 0)].f;",
    "export const WE = (w: string, after?: string) => WORDS[wi(w, after ? wi(after) : 0)].fe;",
    "/** word `w` (default: the first word) of phrase i (voice_build.py P index): unambiguous anchors */",
    "export const PWi = (i: number, w?: string) => {",
    "  const k = WORDS.findIndex((x) => x.p === i && (w === undefined || norm(x.w) === norm(w)));",
    "  if (k < 0) throw new Error(`phrase word not found: ${i} ${w}`);",
    "  return k;",
    "};",
    "export const PW = (i: number, w?: string) => WORDS[PWi(i, w)].f;",
    "export const PWE = (i: number, w?: string) => WORDS[PWi(i, w)].fe;",
    "export const hasPhrase = (i: number) => PHRASES.some((q) => q.i === i);",
]
out.write_text("\n".join(L) + "\n", encoding="utf-8")
print(f"{len(words)} words, {len(phr)} phrases, voice end frame {round(words[-1]['e'] * FPS)} -> {out}")
