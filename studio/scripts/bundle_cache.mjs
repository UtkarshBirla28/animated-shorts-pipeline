// SHARED REMOTION BUNDLE (pipeline, 2026-11-20). One webpack bundle per entry + source state, reused by every
// kit_render / stills / render call until a source file or an asset changes. Used by scripts/kit_render.mjs,
// stills.mjs, render.mjs.        const { serveUrl } = await getBundle({ entry, studio, log });
// - Key: a FAST fingerprint = path + size + mtime of every code file under studio/src (notes .md / .py / .txt / backups
//   skipped), package.json, package-lock.json, tsconfig.json, remotion.config.ts, every file under studio/public, the
//   pinned @remotion/bundler version and the entry path. KIT_BUNDLE_HASH=content hashes the code files' contents instead.
// - public/ is HARD-LINKED into the bundle instead of copied (no 567 MB copy; same bytes; deleting a bundle with any tool
//   only removes the links, never studio/public). index.html is generated by bundle() exactly as before.
// - Concurrency: one builder per key (lock dir `<key>.lock` holding the builder's pid); it builds into
//   `<key>.build-<pid>-<t>` and renames to `<key>` only when complete, so a reader never sees a half-built bundle;
//   other callers wait for it.
// - Each process using a bundle leaves `<key>.users/<pid>`; the sweep never deletes a bundle that has a live user, that
//   was used in the last 2 hours, or that is one of the 3 newest.
// - KIT_BUNDLE=off -> the old behaviour (a private bundle with a full copy of public/, deleted at exit).
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { createRequire } from "node:module";

const require_ = createRequire(import.meta.url);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const alive = (pid) => { if (!pid) return false; if (pid === process.pid) return true; try { process.kill(pid, 0); return true; } catch (e) { return e.code === "EPERM"; } };
const KEEP_MS = 2 * 3600e3, KEEP_NEWEST = 3, LOCK_STALE_MS = 20 * 60e3;
// notes / python / backups next to the code are never imported by the bundle: an edit to them must not rebuild it
const SKIP = /\.(md|py|txt|log|orig)$|\.bak/i;
const walk = (d, out, skip) => {
  let es; try { es = fs.readdirSync(d, { withFileTypes: true }); } catch { return; }
  for (const e of es) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p, out, skip); else if (!skip || !skip.test(e.name)) out.push(p); }
};

/** fingerprint of everything the bundle depends on (node_modules: package-lock stands for them) */
export function bundleKey({ entry, studio, withPublic = true }) {
  const mode = process.env.KIT_BUNDLE_HASH === "content" ? "content" : "stat";
  const h = crypto.createHash("sha1");
  let bundlerVersion = "?";
  try { bundlerVersion = JSON.parse(fs.readFileSync(path.join(studio, "node_modules/@remotion/bundler/package.json"), "utf8")).version; } catch {}
  h.update(JSON.stringify({ v: 2, mode, withPublic, entry: path.relative(studio, entry).split(path.sep).join("/"), bundlerVersion }));
  const code = [];
  walk(path.join(studio, "src"), code, SKIP);
  for (const f of ["package.json", "package-lock.json", "tsconfig.json", "remotion.config.ts"]) code.push(path.join(studio, f));
  const pub = [];
  if (withPublic) walk(path.join(studio, "public"), pub, null);
  const add = (f, content) => {
    h.update(path.relative(studio, f)); h.update("\0");
    try { if (content) h.update(fs.readFileSync(f)); else { const s = fs.statSync(f); h.update(`${s.size}:${Math.floor(s.mtimeMs)}`); } } catch { h.update("missing"); }
    h.update("\0");
  };
  for (const f of code.sort()) add(f, mode === "content");
  for (const f of pub.sort()) add(f, false);
  return { key: h.digest("hex").slice(0, 16), files: code.length, publicFiles: pub.length, mode };
}

const removeBundleDir = (dir) => {
  // public/ inside a bundle is hard links (or, in an old build, a junction): unlink a junction first, never follow it
  const p = path.join(dir, "public");
  try { if (fs.lstatSync(p).isSymbolicLink()) fs.rmdirSync(p); } catch {}
  try { fs.rmSync(dir, { recursive: true, force: true }); } catch {}
};
const liveUsers = (usersDir) => {
  let n = 0;
  try { for (const f of fs.readdirSync(usersDir)) { const pid = Number(f); if (alive(pid)) n++; else try { fs.rmSync(path.join(usersDir, f), { force: true }); } catch {} } } catch {}
  return n;
};

/** delete old bundles nobody uses (and dead builders' leftovers) */
export function sweepBundles(root, currentKey) {
  let names; try { names = fs.readdirSync(root); } catch { return; }
  const now = Date.now();
  for (const n of names) {
    const m = /^([0-9a-f]{16})\.build-(\d+)-/.exec(n);
    if (m && !alive(Number(m[2]))) removeBundleDir(path.join(root, n));
    const g = /^srcgraph-[0-9a-f]+\.json$/.exec(n);
    if (g) { try { if (now - fs.statSync(path.join(root, n)).mtimeMs > 24 * 3600e3) fs.rmSync(path.join(root, n), { force: true }); } catch {} }
  }
  const bundles = names.filter((n) => /^[0-9a-f]{16}$/.test(n)).map((n) => {
    let used = 0; try { used = fs.statSync(path.join(root, n + ".used")).mtimeMs; } catch { try { used = fs.statSync(path.join(root, n)).mtimeMs; } catch {} }
    return { n, used };
  }).sort((a, b) => b.used - a.used);
  bundles.forEach((b, i) => {
    if (b.n === currentKey || i < KEEP_NEWEST || now - b.used < KEEP_MS) return;
    if (liveUsers(path.join(root, b.n + ".users")) > 0) return;
    if (fs.existsSync(path.join(root, b.n + ".lock"))) return;
    removeBundleDir(path.join(root, b.n));
    for (const s of [".users", ".used"]) try { fs.rmSync(path.join(root, b.n + s), { recursive: true, force: true }); } catch {}
  });
}

/** leaked Chrome profiles (`puppeteer_dev_chrome_profile-*`, left by killed renders): delete those older than `minAgeMs`
 *  that no Chrome uses. In use = Chrome's exclusive `lockfile` cannot be opened, or the folder cannot be renamed (Windows
 *  refuses to rename a folder with open files). A profile is only deleted after it was renamed away. */
export function sweepChromeProfiles(tmp, minAgeMs = 30 * 60e3) {
  let names; try { names = fs.readdirSync(tmp); } catch { return { removed: 0, inUse: 0 }; }
  const now = Date.now(); let removed = 0, inUse = 0;
  for (const n of names) {
    const p = path.join(tmp, n);
    if (/^puppeteer_dev_chrome_profile-.*\.del-\d+$/.test(n)) { try { fs.rmSync(p, { recursive: true, force: true }); } catch {} continue; }
    if (!/^puppeteer_dev_chrome_profile-[^.]+$/.test(n)) continue;
    let st; try { st = fs.statSync(p); } catch { continue; }
    if (!st.isDirectory() || now - st.mtimeMs < minAgeMs) continue;
    const lf = path.join(p, "lockfile");
    if (fs.existsSync(lf)) { try { fs.closeSync(fs.openSync(lf, "r+")); } catch { inUse++; continue; } }
    const gone = `${p}.del-${process.pid}`;
    try { fs.renameSync(p, gone); } catch { inUse++; continue; }
    try { fs.rmSync(gone, { recursive: true, force: true }); removed++; } catch {}
  }
  return { removed, inUse };
}

/** webpack-bundle `entry` into `outDir` with public/ hard-linked instead of copied */
async function buildInto({ entry, publicDir, outDir }) {
  const bundlerDist = path.dirname(require_.resolve("@remotion/bundler"));
  const copyMod = require_(path.join(bundlerDist, "copy-dir.js"));
  const orig = copyMod.copyDir;
  const pubAbs = path.resolve(publicDir);
  // bundle.js calls `(0, copy_dir_1.copyDir)(...)` through the module object, so this swap is seen (CommonJS exports)
  copyMod.copyDir = async (args) => {
    if (path.resolve(args.src) !== pubAbs) return orig(args);
    let n = 0;
    const link = (src, dest) => {
      fs.mkdirSync(dest, { recursive: true });
      for (const e of fs.readdirSync(src, { withFileTypes: true })) {
        const s = path.join(src, e.name), d = path.join(dest, e.name);
        if (e.isDirectory()) link(s, d);
        else if (e.isSymbolicLink()) fs.symlinkSync(fs.realpathSync(s), d); // as copy-dir.js does
        else { try { fs.linkSync(s, d); } catch { fs.copyFileSync(s, d); } n++; }
      }
    };
    link(pubAbs, args.dest);
    return n;
  };
  try {
    const { bundle } = await import("@remotion/bundler");
    return await bundle({ entryPoint: entry, publicDir: pubAbs, outDir });
  } finally { copyMod.copyDir = orig; }
}

/**
 * Returns { serveUrl, key, built, ms }. `bundleDir` (from --bundle) is used as-is (never built, never deleted).
 */
export async function getBundle({ entry, studio, publicDir = path.join(studio, "public"), log = console.log, bundleDir = null }) {
  const t0 = Date.now();
  try { const r = sweepChromeProfiles(process.env.REMOTION_TMP || path.resolve(studio, "../_remotion-tmp")); if (r.removed) log(`sweep: removed ${r.removed} leaked Chrome profile(s)`); } catch {}
  if (bundleDir) {
    const d = path.resolve(bundleDir);
    if (!fs.existsSync(path.join(d, "index.html"))) throw new Error(`--bundle ${d}: no index.html there`);
    log(`bundle: using the given ${d}`);
    const cur = bundleKey({ entry, studio }).key;
    const stale = /^[0-9a-f]{16}$/.test(path.basename(d)) ? path.basename(d) !== cur : null;
    if (stale) log(`bundle: WARNING the sources changed since this bundle was built (now ${cur}): it shows the older code`);
    return { serveUrl: d, key: "given", built: false, ms: 0, stale };
  }
  if (process.env.KIT_BUNDLE === "off") {
    const { bundle } = await import("@remotion/bundler");
    const serveUrl = await bundle({ entryPoint: entry, publicDir });
    const clean = () => { try { fs.rmSync(serveUrl, { recursive: true, force: true }); } catch {} };
    process.on("exit", clean);
    return { serveUrl, key: "private", built: true, ms: Date.now() - t0 };
  }
  const root = path.join(process.env.REMOTION_TMP || path.resolve(studio, "../_remotion-tmp"), "kitbundles");
  fs.mkdirSync(root, { recursive: true });
  let me = null;
  const unreg = () => { if (me) try { fs.rmSync(me, { force: true }); } catch {} me = null; };
  process.on("exit", unreg);
  let waitedFor = "";
  for (;;) {
    // (re)compute the key: after waiting for another builder, the sources may have moved on
    const { key, files, publicFiles, mode } = bundleKey({ entry, studio });
    const final = path.join(root, key), lock = final + ".lock", users = final + ".users";
    // register as a user of this key before anything can sweep it
    unreg(); fs.mkdirSync(users, { recursive: true }); me = path.join(users, String(process.pid)); fs.writeFileSync(me, new Date().toISOString());
    const done = (built) => {
      try { fs.writeFileSync(final + ".used", new Date().toISOString()); } catch {}
      try { sweepBundles(root, key); } catch {}
      const ms = Date.now() - t0;
      log(`bundle: ${built ? "built" : "reused"} ${path.relative(studio, final).split(path.sep).join("/")} in ${(ms / 1000).toFixed(1)} s`);
      return { serveUrl: final, key, built, ms };
    };
    if (fs.existsSync(path.join(final, "index.html"))) return done(false);
    let gotLock = false;
    try { fs.mkdirSync(lock); gotLock = true; fs.writeFileSync(path.join(lock, "owner"), `${process.pid} ${new Date().toISOString()}`); } catch (e) { if (e.code !== "EEXIST") throw e; }
    if (gotLock) {
      const unlock = () => { try { fs.rmSync(lock, { recursive: true, force: true }); } catch {} };
      process.on("exit", unlock);
      try {
        if (fs.existsSync(path.join(final, "index.html"))) return done(false);
        const out = `${final}.build-${process.pid}-${Date.now()}`;
        log(`bundle: building ${key} (${files} code files, ${publicFiles} assets, ${mode} key) ...`);
        try {
          await buildInto({ entry, publicDir, outDir: out });
        } catch (e) { removeBundleDir(out); throw e; }
        // a file changed while webpack ran: the bundle may hold a mix, so it must not be shared under this key; this
        // call uses it privately (as before the cache) and it is deleted when this process ends
        const after = bundleKey({ entry, studio }).key;
        if (after !== key) {
          log(`bundle: sources changed during the build (${key} -> ${after}); using it for this call only`);
          process.on("exit", () => removeBundleDir(out));
          return { serveUrl: out, key, built: true, ms: Date.now() - t0, private: true };
        }
        if (fs.existsSync(final)) removeBundleDir(final); // a broken one (no index.html)
        for (let i = 0; ; i++) { try { fs.renameSync(out, final); break; } catch (e) { if (i >= 20) { removeBundleDir(out); throw e; } await sleep(500); } }
        return done(true);
      } finally { unlock(); }
    }
    // someone else builds this key: wait until it is there or the lock is gone (then re-key), or take over a stale lock
    for (;;) {
      if (fs.existsSync(path.join(final, "index.html"))) break;
      let owner = ""; try { owner = fs.readFileSync(path.join(lock, "owner"), "utf8"); } catch {}
      const opid = Number(owner.split(" ")[0]);
      let age = 0; try { age = Date.now() - fs.statSync(lock).mtimeMs; } catch { break; }
      if ((owner && !alive(opid)) || age > LOCK_STALE_MS || (!owner && age > 30e3)) { try { fs.rmSync(lock, { recursive: true, force: true }); } catch {} break; }
      if (waitedFor !== key) { log(`bundle: ${key} is being built by pid ${opid || "?"}; waiting for it`); waitedFor = key; }
      await sleep(1500);
    }
  }
}
