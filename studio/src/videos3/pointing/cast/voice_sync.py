# RE-TIME THE CAST TO A NEW VOICE TAKE (owner CAST). Run from anywhere:
#   python studio/src/videos3/pointing/cast/voice_sync.py [path/to/words.json]
# default: sound/pointing/voice/_full/words.json (a list of {"w": word, "s": start s, "e": end s}).
# It rewrites ONLY the data rows of cast/voice_v1.ts. Nothing else is needed: the lip-sync (timing.ts) and every acting
# beat (beats.ts: keyed to WORDS) follow. Until the voice is LOCKED the take is used SHOT-RELATIVE (the shot table keeps
# its frames; inside each shot the words take the take's rhythm). When the voice locks and words.ts + shots.ts are
# regenerated by the lead's tools, timing.ts switches to words.ts by itself (absolute times) and this file is ignored.
# After a re-time: render the cast sheet page "beats" (or call beatReport() in acting.ts) and read what does not line up.
import json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, "..", "..", "..", "..", ".."))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "sound", "pointing", "voice", "_full", "words.json")
out = os.path.join(here, "voice_v1.ts")

words = json.load(open(src, encoding="utf-8"))
if isinstance(words, dict):  # {"words": [...]} is accepted too
    words = words.get("words", [])
rows = [w for w in words if str(w.get("w", "")).strip()]
bad = [w for w in rows if not (isinstance(w.get("s"), (int, float)) and isinstance(w.get("e"), (int, float)) and w["e"] >= w["s"])]
if bad:
    sys.exit("voice_sync: %d rows without usable s / e times, e.g. %r" % (len(bad), bad[0]))
if any(rows[i]["s"] < rows[i - 1]["s"] - 1e-6 for i in range(1, len(rows))):
    sys.exit("voice_sync: the words are not in time order")

text = open(out, encoding="utf-8").read()
head_end = text.index("export type VWord")
dur = rows[-1]["e"] if rows else 0.0
rel = os.path.relpath(src, root).replace(os.sep, "/")
head = ("// GENERATED (owner CAST) by cast/voice_sync.py from %s (%d words, %.1f s).\n"
        "// timing.ts uses it SHOT-RELATIVE (each shot's word rhythm, anchored on the shot table) until the voice is locked and\n"
        "// words.ts is generated. Re-make: python studio/src/videos3/pointing/cast/voice_sync.py [words.json]\n") % (rel, len(rows), dur)
body = "export type VWord = { w: string; s: number; e: number };\nexport const VOICE_V1: VWord[] = [\n" + "".join(
    "  { w: %s, s: %.3f, e: %.3f },\n" % (json.dumps(w["w"], ensure_ascii=False), w["s"], w["e"]) for w in rows) + "];\n"
open(out, "w", encoding="utf-8", newline="\n").write(head + body)
print("voice_sync: %d words, %.2f s -> %s" % (len(rows), dur, os.path.relpath(out, root).replace(os.sep, "/")))
gaps = [(rows[i]["w"], rows[i + 1]["w"], rows[i + 1]["s"] - rows[i]["e"]) for i in range(len(rows) - 1)]
big = sorted(gaps, key=lambda g: -g[2])[:6]
print("voice_sync: longest pauses: " + ", ".join("%s|%s %.2f s" % g for g in big))
